-- BOLIFENKO KALANSO — socle multilingue des quiz
-- À exécuter dans le projet Supabase dédié après vérification du schéma existant.
-- Ne modifie aucune question déjà présente et ne publie aucune traduction non validée.

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  question_number integer unique,
  theme text not null default 'sécurité routière',
  difficulty text not null default 'facile',
  question_text text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text,
  correct_option char(1) not null check (correct_option in ('A','B','C','D')),
  explanation text,
  source_reference text,
  content_status text not null default 'draft'
    check (content_status in ('draft','verified','published')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.quiz_translations (
  id bigint generated by default as identity primary key,
  question_id bigint not null
    references public.quiz_questions(id) on delete cascade,
  language_code varchar(10) not null
    check (language_code in ('bam_Latn','fuv_Latn')),
  question_text text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text,
  explanation text,
  audio_question_path text,
  audio_option_a_path text,
  audio_option_b_path text,
  audio_option_c_path text,
  audio_option_d_path text,
  audio_explanation_path text,
  translation_status text not null default 'needs_review'
    check (translation_status in ('needs_review','reviewed','approved')),
  translation_provider text not null,
  reviewed_by text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (question_id, language_code)
);


